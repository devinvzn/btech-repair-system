-- Job activity audit log
-- The live database migration is add_job_activity_audit_log.
-- This file mirrors the production DDL for source control.

create table if not exists public.job_activity (
  id bigint generated by default as identity primary key,
  job_id bigint,
  job_no integer,
  action text not null check (action in ('created','updated','deleted')),
  details jsonb not null default '{}'::jsonb,
  changed_by uuid,
  created_at timestamptz not null default now()
);

create index if not exists job_activity_job_id_idx on public.job_activity (job_id);
create index if not exists job_activity_created_at_idx on public.job_activity (created_at desc);

alter table public.job_activity enable row level security;

drop policy if exists "auth_select_job_activity" on public.job_activity;
create policy "auth_select_job_activity" on public.job_activity
  for select to authenticated using (true);

revoke all on public.job_activity from anon;
grant select on public.job_activity to authenticated;

create or replace function public.log_job_activity()
returns trigger
language plpgsql
security definer
set search_path = public, pg_catalog
as $$
begin
  if tg_op = 'INSERT' then
    insert into public.job_activity (job_id, job_no, action, details, changed_by)
    values (new.id, new.job_no, 'created',
      jsonb_build_object('customer',new.customer,'brand',new.brand,'model',new.model,'status',new.status,'payment_status',new.payment_status,'charge',new.charge,'warranty_of',new.warranty_of),
      auth.uid());
    return new;
  elsif tg_op = 'UPDATE' then
    insert into public.job_activity (job_id, job_no, action, details, changed_by)
    values (new.id, new.job_no, 'updated',
      jsonb_build_object('customer',new.customer,'brand',new.brand,'model',new.model,'status',new.status,'payment_status',new.payment_status,'charge',new.charge,'warranty_of',new.warranty_of,'returned_date',new.returned_date),
      auth.uid());
    return new;
  else
    insert into public.job_activity (job_id, job_no, action, details, changed_by)
    values (old.id, old.job_no, 'deleted',
      jsonb_build_object('customer',old.customer,'brand',old.brand,'model',old.model,'status',old.status,'payment_status',old.payment_status,'charge',old.charge,'warranty_of',old.warranty_of),
      auth.uid());
    return old;
  end if;
end;
$$;

drop trigger if exists jobs_activity_audit on public.jobs;
create trigger jobs_activity_audit
after insert or update or delete on public.jobs
for each row execute function public.log_job_activity();

revoke execute on function public.log_job_activity() from public, anon, authenticated, service_role;
